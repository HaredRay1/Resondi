def para(text, size=10.5, bold=False, italic=False, color=INK, after=5, before=0):
    p = doc.add_paragraph()
    p.paragraph_format.space_after, p.paragraph_format.space_before = Pt(after), Pt(before)
    r = p.add_run(text)
    r.font.size, r.bold, r.italic, r.font.color.rgb = Pt(size), bold, italic, color
    return p


def head(text, size=12.5, before=9):
    return para(text, size=size, bold=True, color=ACCENT, after=3, before=before)


def bullets(items, size=10.5):
    for t in items:
        p = para("•  " + t, size=size, after=3)
        p.paragraph_format.left_indent = Inches(0.25)
        p.paragraph_format.first_line_indent = Inches(-0.15)


def shade(cell, fill):
    pr = cell._tc.get_or_add_tcPr()
    sh = OxmlElement("w:shd"); sh.set(qn("w:val"), "clear"); sh.set(qn("w:fill"), fill); pr.append(sh)


def table(rows, widths):
    t = doc.add_table(rows=0, cols=len(widths)); t.style = "Table Grid"
    for i, row in enumerate(rows):
        cells = t.add_row().cells
        for c, (v, w) in enumerate(zip(row, widths)):
            cells[c].width = Inches(w)
            if c == 0:
                shade(cells[c], "EBD3DE")
            r = cells[c].paragraphs[0].add_run(v); r.font.size = Pt(9.5); r.bold = c == 0
    para("", after=2)



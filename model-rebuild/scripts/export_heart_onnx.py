"""Export the two heart-sound models to ONNX for the app, and write the constants the browser needs.

    segmentation  input feats [1, T, 129]  -> probs [1, T, 4]   (S1, systole, S2, diastole), seed 11
    murmur        input wins  [N, 300, 129] -> prob [N]          (mean of seeds 11/22/33 sigmoids)

Both read the per-recording standardised log-power features of scripts/heart_data.py, rounded to
float16. The app computes those features in app/heartFeatures.js from 16 kHz device audio: an FIR
low-pass and 4x decimation to 4 kHz (constants written here), then exactly the training features.

Also writes app/heartConstants.js: the band-pass SOS and its sosfilt_zi (for an exact sosfiltfilt),
the decimation FIR, the Viterbi advance probability chosen on validation (results/heart-segmentation.json)
and the murmur threshold fixed on validation (results/heart-murmur.json).

    python scripts/export_heart_onnx.py
"""
import json
import os
import sys

import numpy as np
import torch
from scipy.signal import firwin, sosfilt_zi

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))
sys.path.insert(0, HERE)
import heart_data as HD  # noqa: E402
import heart_murmur as HM  # noqa: E402
import heart_seg as HS  # noqa: E402

OUT = os.path.join(ROOT, "deploy", "resondi-heart-v1")
APP = os.path.join(ROOT, "app")
FIR_TAPS, FIR_CUT = 161, 1850.0      # 16 kHz anti-alias low-pass before taking every 4th sample


class MurEnsemble(torch.nn.Module):
    def __init__(self, models):
        super().__init__()
        self.models = torch.nn.ModuleList(models)

    def forward(self, wins):
        return torch.stack([torch.sigmoid(m(wins)) for m in self.models], 0).mean(0)


class SegSoftmax(torch.nn.Module):
    def __init__(self, m):
        super().__init__()
        self.m = m

    def forward(self, feats):
        return torch.softmax(self.m(feats), dim=2)


def main():
    import onnxruntime as ort
    os.makedirs(OUT, exist_ok=True)
    d = np.load(os.path.join(HD.WORK, "data.npz"), allow_pickle=True)
    va = np.where(d["part"] == "validation")[0][:40]
    F = [d["F"][i].astype(np.float32) for i in va]

    # ---- segmentation
    seg = HS.build(); seg.load_state_dict(torch.load(os.path.join(HD.WORK, "seg_s11.pt"))); seg.eval()
    segm = SegSoftmax(seg).eval()
    p_seg = os.path.join(OUT, "resondi-heart-seg-v1.onnx")
    torch.onnx.export(segm, torch.zeros(1, 400, 129), p_seg, input_names=["feats"], output_names=["probs"],
                      dynamic_axes={"feats": {1: "t"}, "probs": {1: "t"}}, opset_version=17, dynamo=False)
    s = ort.InferenceSession(p_seg, providers=["CPUExecutionProvider"])
    dseg = 0.0
    for f in F:
        with torch.no_grad():
            ref = segm(torch.tensor(f)[None]).numpy()
        got = s.run(None, {"feats": f[None]})[0]
        dseg = max(dseg, float(np.abs(ref - got).max()))
    print(f"segmentation ONNX vs PyTorch on {len(F)} validation recordings: max |diff| {dseg:.2e}")
    assert dseg < 1e-4

    # ---- murmur ensemble
    mods = []
    for sd in HM.SEEDS:
        m = HM.build(); m.load_state_dict(torch.load(os.path.join(HD.WORK, f"mur_s{sd}.pt"))); m.eval(); mods.append(m)
    mur = MurEnsemble(mods).eval()
    p_mur = os.path.join(OUT, "resondi-heart-murmur-v1.onnx")
    torch.onnx.export(mur, torch.zeros(2, HM.CROP, 129), p_mur, input_names=["wins"], output_names=["prob"],
                      dynamic_axes={"wins": {0: "n"}, "prob": {0: "n"}}, opset_version=17, dynamo=False)
    s = ort.InferenceSession(p_mur, providers=["CPUExecutionProvider"])
    dmur = 0.0
    for f in F:
        w = HM.windows(f)
        with torch.no_grad():
            ref = mur(torch.tensor(w)).numpy()
        got = s.run(None, {"wins": w})[0]
        dmur = max(dmur, float(np.abs(ref - got).max()))
    print(f"murmur ONNX vs PyTorch on {len(F)} validation recordings: max |diff| {dmur:.2e}")
    assert dmur < 1e-4

    # ---- constants for the browser
    segres = json.load(open(os.path.join(ROOT, "results", "heart-segmentation.json")))
    murres = json.load(open(os.path.join(ROOT, "results", "heart-murmur.json")))
    sos = HD._SOS
    zi = sosfilt_zi(sos)
    nz = min(int((sos[:, 2] == 0).sum()), int((sos[:, 5] == 0).sum()))
    padlen = 3 * (2 * len(sos) + 1 - nz)
    fir = firwin(FIR_TAPS, FIR_CUT, fs=16000)
    const = {
        "ADVANCE": segres["advance_prob_chosen_on_validation"],
        "MURMUR_THRESHOLD": murres["threshold"],
        "SOS": sos.tolist(), "SOS_ZI": zi.tolist(), "PADLEN": padlen,
        "FIR": fir.tolist(),
    }
    lines = ["// Generated by model-rebuild/scripts/export_heart_onnx.py. Do not edit by hand.",
             "// ADVANCE: Viterbi advance probability, chosen on validation patients.",
             "// MURMUR_THRESHOLD: fixed on validation patients for a pre-specified 80% sensitivity (test: 66.7%).",
             "// SOS / SOS_ZI / PADLEN: butter(4, [25, 1900], 'bandpass', fs=4000) for an exact scipy sosfiltfilt.",
             f"// FIR: firwin({FIR_TAPS}, {FIR_CUT}, fs=16000), the 16 kHz -> 4 kHz anti-alias low-pass."]
    for k, v in const.items():
        lines.append(f"export const {k} = {json.dumps(v)};")
    open(os.path.join(APP, "heartConstants.js"), "w").write("\n".join(lines) + "\n")

    meta = {"model_version": "resondi-heart-v1",
            "files": {"segmentation": os.path.basename(p_seg), "murmur": os.path.basename(p_mur)},
            "bytes": {"segmentation": os.path.getsize(p_seg), "murmur": os.path.getsize(p_mur)},
            "constants": {k: const[k] for k in ("ADVANCE", "MURMUR_THRESHOLD", "PADLEN")},
            "training_data": "CirCor DigiScope 1.0.3 (ODC-By), patient-wise split, 564 training patients",
            "evaluation": "189 CirCor test patients: heart rate MAE 3.0 BPM (95% CI 2.5-3.6); S1/S2 found within "
                          "100 ms 96.8%/97.3%; murmur sensitivity 66.7% (50.0-81.8) against a pre-specified 80%, "
                          "specificity 97.1%, AUROC 0.96. Not tested on Resondi device audio.",
            "onnx_vs_pytorch_max_abs_diff": {"segmentation": dseg, "murmur": dmur}}
    json.dump(meta, open(os.path.join(OUT, "model.json"), "w"), indent=1)
    print("wrote", p_seg, os.path.getsize(p_seg), "bytes;", p_mur, os.path.getsize(p_mur), "bytes")
    print("wrote", os.path.join(APP, "heartConstants.js"))


if __name__ == "__main__":
    main()
